-- Azure-MultiAgent Milestone 0.6 — local retail business schema (no transaction operations).
-- No columns distinguish original vs synthetic samples; use the same domain schema for both.
CREATE SCHEMA IF NOT EXISTS retail;

CREATE TABLE IF NOT EXISTS retail.products (
  sku TEXT PRIMARY KEY,
  category TEXT
);
CREATE TABLE IF NOT EXISTS retail.locations (
  location_id TEXT PRIMARY KEY,
  location_type TEXT CHECK (location_type IN ('store','warehouse','other') OR location_type IS NULL)
);
CREATE TABLE IF NOT EXISTS retail.inventory_positions (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  on_hand INTEGER NOT NULL CHECK (on_hand >= 0),
  reserved INTEGER NOT NULL CHECK (reserved >= 0),
  reorder_point INTEGER NOT NULL CHECK (reorder_point >= 0),
  days_until_stockout INTEGER CHECK (days_until_stockout >= 0),
  PRIMARY KEY (sku, location_id)
);
CREATE TABLE IF NOT EXISTS retail.suppliers (
  supplier_id TEXT PRIMARY KEY,
  name TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS retail.supplier_offers (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  supplier_id TEXT NOT NULL REFERENCES retail.suppliers(supplier_id),
  available_qty INTEGER NOT NULL CHECK (available_qty >= 0),
  unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost > 0),
  lead_time_days INTEGER NOT NULL CHECK (lead_time_days >= 0),
  reliability_score NUMERIC(5,4) NOT NULL CHECK (reliability_score BETWEEN 0 AND 1),
  PRIMARY KEY (sku, supplier_id)
);
CREATE TABLE IF NOT EXISTS retail.carrier_services (
  service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  carrier TEXT NOT NULL,
  service_level TEXT NOT NULL,
  UNIQUE (carrier, service_level)
);
CREATE TABLE IF NOT EXISTS retail.shipping_rates (
  service_id BIGINT PRIMARY KEY REFERENCES retail.carrier_services(service_id),
  base_cost NUMERIC(12,2) NOT NULL CHECK (base_cost >= 0),
  per_unit_cost NUMERIC(12,2) NOT NULL CHECK (per_unit_cost >= 0),
  eta_days INTEGER NOT NULL CHECK (eta_days >= 0)
);
CREATE TABLE IF NOT EXISTS retail.carrier_destinations (
  service_id BIGINT NOT NULL REFERENCES retail.carrier_services(service_id),
  destination_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  PRIMARY KEY (service_id, destination_id)
);
CREATE TABLE IF NOT EXISTS retail.retail_prices (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  current_price NUMERIC(12,2) NOT NULL CHECK (current_price > 0),
  unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
  floor_price NUMERIC(12,2) NOT NULL CHECK (floor_price > 0),
  ceiling_price NUMERIC(12,2) NOT NULL CHECK (ceiling_price >= floor_price),
  category TEXT NOT NULL,
  PRIMARY KEY (sku, location_id)
);
-- Additional scenario data for approved test coverage.
CREATE TABLE IF NOT EXISTS retail.inbound_inventory (
  inbound_id TEXT PRIMARY KEY,
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  expected_date DATE,
  status TEXT NOT NULL CHECK (status IN ('planned','in_transit','received','cancelled'))
);
CREATE TABLE IF NOT EXISTS retail.inventory_policies (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  target_stock INTEGER NOT NULL CHECK (target_stock >= 0),
  safety_stock INTEGER NOT NULL CHECK (safety_stock >= 0),
  PRIMARY KEY (sku, location_id)
);
CREATE TABLE IF NOT EXISTS retail.location_transfer_rules (
  origin_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  destination_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  eligible BOOLEAN NOT NULL,
  transit_days INTEGER CHECK (transit_days >= 0),
  PRIMARY KEY (origin_id,destination_id),
  CHECK (origin_id <> destination_id)
);
CREATE TABLE IF NOT EXISTS retail.demand_history (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  demand_date DATE NOT NULL,
  units_sold INTEGER NOT NULL CHECK (units_sold >= 0),
  PRIMARY KEY (sku,location_id,demand_date)
);
CREATE TABLE IF NOT EXISTS retail.shipping_lanes (
  origin_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  destination_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  service_id BIGINT NOT NULL REFERENCES retail.carrier_services(service_id),
  eligible BOOLEAN NOT NULL,
  PRIMARY KEY (origin_id,destination_id,service_id),
  CHECK (origin_id <> destination_id)
);
CREATE TABLE IF NOT EXISTS retail.pricing_history (
  sku TEXT NOT NULL REFERENCES retail.products(sku),
  location_id TEXT NOT NULL REFERENCES retail.locations(location_id),
  effective_date DATE NOT NULL,
  price NUMERIC(12,2) NOT NULL CHECK (price > 0),
  PRIMARY KEY (sku,location_id,effective_date)
);
